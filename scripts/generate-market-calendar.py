"""Regenerate the bundled cash-session exceptions with uv run scripts/generate-market-calendar.py."""

from datetime import time
from pathlib import Path
import json

import exchange_calendars as calendars
import pandas as pd


FIRST_YEAR, LAST_YEAR = 2025, 2035
MARKETS = {
    "XNYS": (time(9, 30), time(16)),
    "XLON": (time(8), time(16, 30)),
    "XTKS": (time(9), time(15, 30)),
}
DESTINATION = Path(__file__).resolve().parents[1] / "src/market_sessions/calendar_data.rs"


def calendar_rows(mic, regular_hours, start, end):
    calendar = calendars.get_calendar(mic, start=start, end=end)
    names = calendar.regular_holidays.holidays(start, end, return_name=True).to_dict()
    schedule = calendar.schedule
    # Weekends are handled directly by the clock. Fail loudly if that assumption changes.
    if (schedule.index.day_of_week >= 5).any():
        raise ValueError(f"{mic} has a weekend session")
    for day in pd.date_range(start, end, freq="B"):
        if day not in schedule.index:
            name = names.get(day, "Exchange holiday").split(" (")[0]
            if name.startswith("Weekend "):
                name = f"{name.removeprefix('Weekend ')} (observed)"
            change = f"Holiday({json.dumps(name, ensure_ascii=False)})"
        else:
            session = schedule.loc[day]
            opening = session.open.tz_convert(calendar.tz).time()
            closing = session.close.tz_convert(calendar.tz).time()
            if (opening, closing) == regular_hours:
                continue
            assert not (opening.second or closing.second)
            change = f"Hours(({opening.hour}, {opening.minute}), ({closing.hour}, {closing.minute}))"
        yield f"    (({day.year}, {day.month}, {day.day}), {change}),"


def main():
    lines = [
        f"// Generated by scripts/generate-market-calendar.py with exchange_calendars {calendars.__version__}.",
        "use super::calendar::{DateException, ExceptionTable};",
        "use DateException::{Holiday, Hours};",
        "",
        f"pub(super) const YEARS: std::ops::RangeInclusive<i32> = {FIRST_YEAR}..={LAST_YEAR};",
    ]
    for mic, regular_hours in MARKETS.items():
        lines.extend(["", "#[rustfmt::skip]", f"pub(super) const {mic}: ExceptionTable = &["])
        lines.extend(calendar_rows(mic, regular_hours, f"{FIRST_YEAR}-01-01", f"{LAST_YEAR}-12-31"))
        lines.append("];")
    DESTINATION.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
